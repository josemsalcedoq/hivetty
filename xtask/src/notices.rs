//! `cargo xtask notices`: writes THIRD_PARTY_NOTICES.md, the license of every crate compiled
//! into hivetty (F6-15). Release packages ship it next to the binary.

use std::collections::BTreeMap;
use std::process::Command;

use anyhow::{Context, Result, bail};
use serde_json::Value;

/// Crates of this workspace (not third party).
fn is_ours(name: &str) -> bool {
    name.starts_with("hv-") || name == "xtask"
}

/// Builds the notices from `cargo metadata` for the shipped binary's dependency graph.
pub(crate) fn generate() -> Result<String> {
    let output = Command::new("cargo")
        .args(["metadata", "--format-version", "1", "--locked"])
        .output()
        .context("cannot run cargo metadata")?;
    if !output.status.success() {
        bail!(
            "cargo metadata failed: {}",
            String::from_utf8_lossy(&output.stderr)
        );
    }
    let meta: Value = serde_json::from_slice(&output.stdout).context("bad cargo metadata")?;
    render(&meta)
}

/// The packages reachable from hv-app (normal and build dependencies; not dev-only).
fn shipped(meta: &Value) -> Result<Vec<&Value>> {
    let packages: BTreeMap<&str, &Value> = meta["packages"]
        .as_array()
        .context("no packages")?
        .iter()
        .filter_map(|p| Some((p["id"].as_str()?, p)))
        .collect();
    let nodes: BTreeMap<&str, &Value> = meta["resolve"]["nodes"]
        .as_array()
        .context("no resolve graph")?
        .iter()
        .filter_map(|n| Some((n["id"].as_str()?, n)))
        .collect();
    let root = packages
        .values()
        .find(|p| p["name"] == "hv-app")
        .and_then(|p| p["id"].as_str())
        .context("hv-app not found")?;
    let mut seen = std::collections::BTreeSet::new();
    let mut stack = vec![root];
    while let Some(id) = stack.pop() {
        if !seen.insert(id) {
            continue;
        }
        let Some(node) = nodes.get(id) else { continue };
        for dep in node["deps"].as_array().into_iter().flatten() {
            let kinds = dep["dep_kinds"].as_array().cloned().unwrap_or_default();
            let only_dev = !kinds.is_empty() && kinds.iter().all(|k| k["kind"] == "dev");
            if !only_dev && let Some(pkg) = dep["pkg"].as_str() {
                stack.push(pkg);
            }
        }
    }
    let mut out: Vec<&Value> = seen
        .into_iter()
        .filter_map(|id| packages.get(id).copied())
        .filter(|p| !p["name"].as_str().is_some_and(is_ours))
        .collect();
    out.sort_by_key(|p| {
        (
            p["name"].as_str().unwrap_or_default().to_owned(),
            p["version"].as_str().unwrap_or_default().to_owned(),
        )
    });
    Ok(out)
}

fn render(meta: &Value) -> Result<String> {
    let packages = shipped(meta)?;
    let mut by_license: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut table = String::new();
    for p in &packages {
        let name = p["name"].as_str().unwrap_or_default();
        let version = p["version"].as_str().unwrap_or_default();
        let license = p["license"].as_str().unwrap_or("see repository");
        let repo = p["repository"].as_str().unwrap_or("");
        table.push_str(&format!("| {name} | {version} | {license} | {repo} |\n"));
        by_license
            .entry(license.to_owned())
            .or_default()
            .push(format!("{name} {version}"));
    }
    let mut out = String::from(
        "# Third-party notices\n\nhivetty includes the following open-source crates. Each is \
         used under the license shown; the full license texts are in each crate's repository \
         and in the source published on crates.io. Fonts bundled by egui (Ubuntu-Light, Hack, \
         Noto Emoji) are under the Ubuntu Font Licence 1.0 and the SIL Open Font License 1.1.\n\n\
         Generated by `cargo xtask notices`.\n\n## Summary by license\n\n",
    );
    for (license, crates) in &by_license {
        out.push_str(&format!("- **{license}**: {} crates\n", crates.len()));
    }
    out.push_str(&format!(
        "\n## Crates ({})\n\n| Crate | Version | License | Repository |\n|---|---|---|---|\n",
        packages.len()
    ));
    out.push_str(&table);
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dev_only_dependencies_and_our_crates_are_left_out() {
        let meta = serde_json::json!({
            "packages": [
                {"id": "app", "name": "hv-app", "version": "0.0.0", "license": "MIT"},
                {"id": "a", "name": "alpha", "version": "1.0.0", "license": "MIT OR Apache-2.0", "repository": "https://example.com/a"},
                {"id": "t", "name": "testlib", "version": "2.0.0", "license": "MIT"},
                {"id": "b", "name": "beta", "version": "0.3.0", "license": "Zlib"}
            ],
            "resolve": {"nodes": [
                {"id": "app", "deps": [
                    {"pkg": "a", "dep_kinds": [{"kind": null}]},
                    {"pkg": "t", "dep_kinds": [{"kind": "dev"}]}
                ]},
                {"id": "a", "deps": [{"pkg": "b", "dep_kinds": [{"kind": "build"}]}]},
                {"id": "t", "deps": []},
                {"id": "b", "deps": []}
            ]}
        });
        let text = render(&meta).unwrap();
        assert!(text.contains("| alpha | 1.0.0 | MIT OR Apache-2.0 |"));
        assert!(text.contains("| beta | 0.3.0 | Zlib |"));
        assert!(!text.contains("testlib"));
        assert!(!text.contains("| hv-app |"));
    }
}
